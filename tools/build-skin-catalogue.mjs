// Generated catalogue from the pinned Paper-Yuan research snapshot; no asset URLs or runtime downloads.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
export function catalogueFrom(research) {
  const out = [];
  const ids = new Set();
  for (const [charId, skins] of Object.entries(research.skins || {})) {
    if (!/^char_[a-zA-Z0-9_]+$/.test(charId)) throw new Error('unsafe charId');
    for (const s of skins) {
      if (typeof s.skinId !== 'string' || !s.skinId.startsWith(`${charId}@`) || s.skinId.length > 80 || ids.has(s.skinId) || !/^[a-zA-Z0-9_-]+$/.test(s.stem)) throw new Error('unsafe skin descriptor');
      ids.add(s.skinId);
      out.push({ id: s.skinId, charId, name: s.name || '', group: s.group || '', stem: s.stem });
    }
  }
  return out.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const catalogue = catalogueFrom(JSON.parse(await readFile(process.argv[2], 'utf8')));
  await writeFile('shared/skin-catalogue.js', '// Generated by tools/build-skin-catalogue.mjs. Source: Paper-Yuan/Stronghold-Protocol\n// 06cd3d0aafee6d9b1a3c542414fb847e16871a4d. GPL-3.0-or-later; game assets: NOTICE.md.\nexport const SKIN_CATALOGUE = Object.freeze(' + JSON.stringify(catalogue, null, 2) + '.map(Object.freeze));\n');
  console.log(JSON.stringify({ skins: catalogue.length, chars: new Set(catalogue.map(s => s.charId)).size }));
}
