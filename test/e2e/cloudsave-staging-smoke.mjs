// Opt-in, short staging UI startup check; no password field entry or gameplay.
import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
if (process.env.SP_CLOUD_UI_SMOKE !== '1') process.exit(0);
const base = process.env.SP_URL;
assert.equal(base, 'http://127.0.0.1:3001');
const browser = await puppeteer.connect({ browserURL: 'http://127.0.0.1:9225', protocolTimeout: 45000 });
const context = await browser.createBrowserContext();
const page = await context.newPage();
const errors = [], requests = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('request', (r) => { if (r.url().includes('/api/cloud-save/')) requests.push(r.method()); });
try {
  await page.setViewport({ width: 1280, height: 720 });
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.title-stats', { timeout: 45000 });
  await page.click('.title-stats');
  await page.waitForSelector('[data-tab="cloud"]');
  await page.click('button[data-tab="cloud"]');
  await page.waitForSelector('[data-testid="cloud-save-panel"] input[type=password]');
  assert.equal(await page.$$eval('[data-testid="cloud-save-panel"] input[type=checkbox]', (inputs) => inputs.length), 2);
  const text = await page.$eval('[data-testid="cloud-save-panel"]', (el) => el.textContent);
  assert.match(text, /HTTP.*不加密/); assert.match(text, /不会自动上传/);
  assert.equal(requests.length, 0, 'opening statistics/cloud panel never uploads');
  assert.deepEqual(await page.$eval('[data-testid=cloud-save-panel] input[type=text]', el => ({name:el.value, readonly:el.readOnly})), {name:'', readonly:true});
  assert.deepEqual(await page.$eval('input[type=password]', el => ({min:el.minLength,max:el.maxLength})), {min:8,max:128});
  await page.click('[data-cloud-action="upload"]');
  await page.waitForFunction(() => document.querySelector('[data-testid="cloud-save-panel"] [role=status]')?.textContent.includes('请先使用玩家名进入游戏'));
  assert.equal(requests.length, 0, 'blank credentials fail locally');
  assert.equal(await page.$eval('input[type=password]', (el) => el.value), '');
  const b = await page.$eval('[data-testid="cloud-save-panel"]', (el) => { const r = el.getBoundingClientRect(); return { width: r.width, top: r.top, height: r.height }; });
  assert.ok(b.width > 200);
  await page.screenshot({ path: '/evidence/staging-cloud-panel.png', fullPage: true });
  await page.click('.st-back');
  await page.type('.title-login input', '云存档界面检查');
  await page.click('.title-login button.btn--primary');
  await page.waitForFunction(() => globalThis.__SP__?.store.get().connection.status === 'online' && document.querySelector('.lobby-screen'), { timeout: 30000 });
  await page.evaluate(async () => { (await import('/js/screens/stats.js')).openStats(); });
  await page.waitForSelector('button[data-tab=cloud]');
  await page.click('button[data-tab=cloud]');
  await page.waitForFunction(() => document.querySelector('[data-testid=cloud-save-panel] input[type=text]')?.value === '云存档界面检查');
  await page.evaluate(async () => { (await import('/js/screens/title.js')).enterSession('身份更新检查'); });
  await page.waitForFunction(() => document.querySelector('[data-testid=cloud-save-panel] input[type=text]')?.value === '身份更新检查');
  await page.click('[data-cloud-action=upload]');
  await page.waitForFunction(() => document.querySelector('[data-testid=cloud-save-panel] [role=status]')?.textContent.includes('恢复密码须为8–128字'));
  assert.equal(requests.length,0);
  assert.equal(await page.$eval('input[type=password]', el => el.value), '');
  assert.deepEqual(errors, []);
  const health = await (await fetch(base + '/healthz')).json();
  console.log(JSON.stringify({ base, build: health.build, titleRendered: true, connectionOnline: true, fixedLiveName: true, loginNameChangesObserved: true, passwordRange: '8–128', cloudTabOpened: true, choices: 2, httpWarning: true, noAutoUpload: true, blankInputStatusVisible: true, passwordFieldUntouchedAndEmpty: true, pageErrors: errors, bounds: b, fullGameplayAcceptance: 'reserved to user' }, null, 2));
} finally { await context.close(); await browser.disconnect(); }
